"""Temperature cleaning using loop, comprehension, and map/filter."""
def loop_valid(xs):
    out=[]
    for x in xs:
        if -5<=x<=5: out.append(x)
    return out
def comp_valid(xs): return [x for x in xs if -5<=x<=5]
def functional_valid(xs): return list(filter(lambda x:-5<=x<=5,xs))
def main():
    readings=[-6.0,-2.0,2.5,5.1,4.0]
    valid=comp_valid(readings); print('valid C:',valid); print('Fahrenheit:',[x*9/5+32 for x in valid]); print('alarm minutes:',[i for i,x in enumerate(readings,1) if not 2<=x<=8])
    print('identical:',loop_valid(readings)==comp_valid(readings)==functional_valid(readings)); print('edge cases:',comp_valid([]),comp_valid([-9,9]))
    for label,case in [('all-valid',[0.0,2.0,5.0]),('all-invalid',[-8.0,9.0]),('empty',[])]:
        results=[fn(case) for fn in (loop_valid,comp_valid,functional_valid)]
        print(label,'identical:',results[0]==results[1]==results[2],results[0])
    print('dict comprehension:',{i:x for i,x in enumerate(readings,1) if -5<=x<=5}); print('set comprehension:',{x for x in readings if -5<=x<=5})
    print('comprehension: [expression for item in iterable if condition]; generators defer values and use O(1) iterator memory, lists use O(k). Comprehensions become hard to scan with nested/complex conditions.')
    print('all-valid/all-invalid/empty produce identical outputs across all three implementations.')
    print('complexity: O(n) time; list O(k) output memory. Comprehension is concise but not always fastest; measured timings are generated by experiments/run_all_benchmarks.py.')
if __name__=='__main__': main()
